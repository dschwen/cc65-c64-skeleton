#ifndef GAME_BANKS_H
#define GAME_BANKS_H

/*
 * EasyFlash bank assignments. oscar64 gives each bank a full 16 KiB window
 * ($8000-$BFFF) and needs no byte-exact packing; with 64 banks available
 * and this game's banked content well under that, every service gets a
 * bank of its own and every room gets one too. Two regions placed in the
 * same bank are a compile error ("Overlapping data section"), so a
 * collision cannot ship silently - but check this file before extending
 * any contiguous range.
 *
 * Layout: services 1-12, environment modules 13-16, resource banks 17-19,
 * rooms from 24 upward (room N is BANK_ROOM_FIRST + N, room IDs 0-39).
 * Bank 0 is the compiler's startup bank and the compressed resident main.
 */

#define BANK_TYPEINFO       1u  /* cold PlatformObjectTypeInfo records (modules/typeinfo.c) */
#define BANK_ROOM_HELPERS   2u  /* modules/room_helpers.c */
#define BANK_LOOK_HELPERS   3u  /* modules/look_helpers.c */
#define BANK_SCRIPT         4u  /* script/conversation interpreter (modules/script.c) */
#define BANK_INVENTORY      5u  /* modules/inventory.c */
#define BANK_SAVELOAD       6u  /* save/load browser and load flow (modules/saveload.c) */
#define BANK_SAVELOAD_SAVE  7u  /* save encoding and write flow (modules/saveload_save.c) */

/* KERNAL serial-bus disk I/O (src/disk_io.c) - banked because oscar64's
 * krnio_* library pulls in enough code to overflow the resident "main"
 * region (see memmap.h). Called from the SL/SV banks through resident
 * trampolines (platform_disk_read() etc.) - far_call_bank() itself may not
 * be expanded inside a bank. */
#define BANK_DISK_IO        8u

/* Tile/text charsets and the source copy of tile_data/tile_properties
 * (src/assets_data.c). The *resident* copies are plain BSS, deliberately
 * reused as scratch space by the save/load UI while it is running, then
 * reloaded from here afterward. */
#define BANK_ASSET_TILES    9u

/* Boot source for object zone B plus the banked zone C records (type IDs
 * 223-255; src/object_types_data.c). Zone C is on the per-frame draw path,
 * so platform_object_type_get() keeps a one-entry resident cache in front
 * of this bank. */
#define BANK_OBJECT_TYPE_C  10u

/* World-state store/restore code (src/world.c) - only ever invoked from
 * platform_room_enter() and game_world_capture_current(). The delta and
 * baseline *data* stay resident; only the code is banked. */
#define BANK_WORLD_STATE    11u

/* Title screen, its picture and the Moonfen Waltz (modules/title.c,
 * music/waltz_player.h). Runs once, before platform_init(). */
#define BANK_TITLE          12u

/* Environment modules (rooms/env/*.c) - one bank per distinct module;
 * rooms/rooms.manifest maps rooms onto them. Each module is small and is
 * copied whole to $7E00 at room entry - see memmap.h's ENVCODE_* macros. */
#define BANK_ENV_RAIN            13u
#define BANK_ENV_TAVERN          14u
#define BANK_ENV_TAVERN_MUFFLED  15u
#define BANK_ENV_CELLAR          16u

/* Resource banks: one shared bank per PLATFORM_RESOURCE_KIND_* (src/
 * platform.h), each generated by tools/generate_script_bank.py with an
 * internal switch on resource ID - one far_call_bank() call site per kind
 * in src/resources.c regardless of how many resources exist. The kinds
 * have independent 0-255 ID spaces, which is why they do not share a bank.
 *
 * Portraits: assets/portraits/<id>, 256 bytes each; up to 32 fit one bank.
 * A 33rd would need a second constant and Makefile group. */
#define BANK_PORTRAIT_FIRST            17u
/* Room scripts: assets/scripts/<room id>.script. */
#define BANK_SCRIPT_ROOM_FIRST         18u
/* Conversations: assets/scripts/conversations/<id>.script. */
#define BANK_SCRIPT_CONVERSATION_FIRST 19u

/* Rooms: room N's record and native handlers live in bank
 * BANK_ROOM_FIRST + N (tools/compile_room.py and the generated
 * build/rooms/room_table.h agree on this formula). Banks 24-63 leave room
 * for IDs 0-39; a 41st room needs a different scheme (e.g. several rooms
 * per bank at fixed offsets). */
#define BANK_ROOM_FIRST     24u

#endif
