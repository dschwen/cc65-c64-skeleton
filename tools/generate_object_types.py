#!/usr/bin/env python3
"""Generate a C header of object-type symbols from assets/objects.cobj.

Every object type with a non-empty name becomes `#define OBJ_<NAME> <id>u`
(name uppercased, runs of non-alphanumerics collapsed to one underscore:
"Guests Broth" -> OBJ_GUESTS_BROTH, "Lit Taper" -> OBJ_LIT_TAPER). The
header is included by generated room code (tools/compile_room.py) and read
as a symbol file by tools/compile_script.py and compile_room.py, so both
.script sources and C fragments can name an item instead of spelling out
its numeric ID. Two types whose names collapse to the same symbol are a
build error - rename one in the asset editor.

The editor stores names as ASCII; tools/prepare_c64_assets.py's PETSCII
conversion only happens on the build copy, so this reads the source file
directly.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

OBJECT_TYPE_BYTES = 64
OBJECT_TYPE_COUNT = 256
OBJECT_NAME_OFFSET = 2
OBJECT_NAME_BYTES = 14


def symbol_for(name: str) -> str:
    collapsed = re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_").upper()
    if not collapsed:
        return ""
    if collapsed[0].isdigit():
        collapsed = "_" + collapsed
    return "OBJ_" + collapsed


def generate(data: bytes, source: Path) -> str:
    expected = OBJECT_TYPE_BYTES * OBJECT_TYPE_COUNT
    if len(data) != expected:
        raise SystemExit(f"{source}: expected {expected} bytes, got {len(data)}")
    lines = [
        "/* Generated by tools/generate_object_types.py from "
        f"{source.as_posix()} - do not edit by hand. */",
        "#ifndef GAME_OBJECT_TYPES_H",
        "#define GAME_OBJECT_TYPES_H",
        "",
    ]
    seen: dict[str, tuple[int, str]] = {}
    for type_id in range(OBJECT_TYPE_COUNT):
        start = type_id * OBJECT_TYPE_BYTES + OBJECT_NAME_OFFSET
        raw = data[start:start + OBJECT_NAME_BYTES].split(b"\0", 1)[0]
        name = raw.decode("ascii", errors="replace").strip()
        if not name:
            continue
        symbol = symbol_for(name)
        if not symbol:
            continue
        if symbol in seen:
            other_id, other_name = seen[symbol]
            raise SystemExit(
                f"{source}: object types {other_id} ({other_name!r}) and "
                f"{type_id} ({name!r}) both produce the symbol {symbol}; "
                "rename one of them"
            )
        seen[symbol] = (type_id, name)
        lines.append(f"#define {symbol:<28} {type_id}u /* {name} */")
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    text = generate(args.input.read_bytes(), args.input)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")
    print(f"{args.input} -> {args.output}")


if __name__ == "__main__":
    main()
