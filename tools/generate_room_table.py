#!/usr/bin/env python3
"""Generate the room dispatch table and the room-to-environment lookup from
rooms/rooms.manifest.

The manifest is the single list of rooms in the build. One room per line:

    # room-id   environment
    00          rain
    02          tavern
    04          none

`room-id` is the two-digit hex ID shared by assets/<id>, rooms/<id>.rc and
assets/scripts/<id>.script; `environment` names a rooms/env/*.c module
(BANK_ENV_<NAME> in src/banks.h) or `none`. The Makefile reads the same
file for its ROOM_IDS list, so adding a room is one manifest line plus the
room's own asset, .rc and .script files.

Outputs (both under build/rooms/, on the include path):

  room_table.h  - ROOM_DECLARE/ROOM_TABLE_ENTRIES for src/room_dispatch.c;
                  room N's code lives in EasyFlash bank BANK_ROOM_FIRST + N,
                  the same formula tools/compile_room.py places it with.
  env_banks.h   - env_bank_for_room() for src/game.c.
"""

from __future__ import annotations

import argparse
from pathlib import Path


def parse_manifest(path: Path) -> list[tuple[int, str]]:
    rooms: list[tuple[int, str]] = []
    seen: set[int] = set()
    for line_no, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) != 2:
            raise SystemExit(f"{path}:{line_no}: expected '<hex room id> <environment|none>'")
        try:
            room_id = int(parts[0], 16)
        except ValueError:
            raise SystemExit(f"{path}:{line_no}: bad room id {parts[0]!r}") from None
        if not 0 <= room_id <= 255:
            raise SystemExit(f"{path}:{line_no}: room id {parts[0]} out of range")
        if room_id in seen:
            raise SystemExit(f"{path}:{line_no}: room {parts[0]} listed twice")
        seen.add(room_id)
        env = parts[1].lower()
        if not env.replace("_", "").isalnum():
            raise SystemExit(f"{path}:{line_no}: bad environment name {parts[1]!r}")
        rooms.append((room_id, env))
    if not rooms:
        raise SystemExit(f"{path}: no rooms listed")
    return rooms


def room_table(rooms: list[tuple[int, str]], source: Path) -> str:
    out = [
        f"/* Generated by tools/generate_room_table.py from {source.as_posix()} - do not edit. */",
        "#ifndef GAME_ROOM_TABLE_H",
        "#define GAME_ROOM_TABLE_H",
        "",
        "#define ROOM_DECLARE(id) \\",
        "    void room##id##_enter_room(void); \\",
        "    void room##id##_enter_tile(void); \\",
        "    uint8_t room##id##_look_at(uint8_t tile_x, uint8_t tile_y); \\",
        "    uint8_t room##id##_use_at(uint8_t tile_x, uint8_t tile_y);",
        "",
    ]
    out += [f"ROOM_DECLARE({room_id:02x})" for room_id, _ in rooms]
    out += [
        "",
        "#undef ROOM_DECLARE",
        "",
        "#define ROOM_ENTRY(id, num) \\",
        "    { num, BANK_ROOM_FIRST + num, room##id##_enter_room, room##id##_enter_tile, \\",
        "      room##id##_look_at, room##id##_use_at }",
        "",
        "#define ROOM_TABLE_ENTRIES \\",
    ]
    entries = [f"    ROOM_ENTRY({room_id:02x}, {room_id}u)" for room_id, _ in rooms]
    out.append(", \\\n".join(entries))
    out += ["", "#endif", ""]
    return "\n".join(out)


def env_banks(rooms: list[tuple[int, str]], source: Path) -> str:
    out = [
        f"/* Generated by tools/generate_room_table.py from {source.as_posix()} - do not edit. */",
        "#ifndef GAME_ENV_BANKS_H",
        "#define GAME_ENV_BANKS_H",
        "",
        "/* Room ID -> environment module bank (rooms/env/*.c, src/banks.h's",
        " * BANK_ENV_* constants); 0xff for a room with no environment module. */",
        "static inline uint8_t env_bank_for_room(uint8_t room_id) {",
        "    switch (room_id) {",
    ]
    for room_id, env in rooms:
        if env == "none":
            continue
        out.append(f"        case 0x{room_id:02x}u: return BANK_ENV_{env.upper()};")
    out += [
        "        default: return 0xffu;",
        "    }",
        "}",
        "",
        "#endif",
        "",
    ]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--room-table", type=Path, required=True)
    parser.add_argument("--env-banks", type=Path, required=True)
    args = parser.parse_args()
    rooms = parse_manifest(args.manifest)
    for path, text in ((args.room_table, room_table(rooms, args.manifest)),
                       (args.env_banks, env_banks(rooms, args.manifest))):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"{args.manifest} -> {path}")


if __name__ == "__main__":
    main()
