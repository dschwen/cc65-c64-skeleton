#!/usr/bin/env python3
"""Wrap every compiled room-script bytecode blob (tools/compile_script.py's
output, one per room) in a single shared oscar64 EasyFlash bank, as
compile-time #embed'd const arrays - the same shape as modules/typeinfo.c's
cold_table, but arrays instead of one table since each resource is a
different size.

All resources fit one 16 KiB bank comfortably today (room scripts total a
few KB), so a single generated bank with an internal `switch` on resource
ID is far cheaper in *resident* code than one far_call_bank() per resource
would be: the switch that picks which resource to copy from lives inside
the bank (irrelevant to the resident budget - src/memmap.h), and
src/resources.c only needs one direct, literal far_call_bank() call site
regardless of how many resources exist. #embed's limit must be a literal
integer (see src/object_types_data.c's header comment), so this script
reads each input file's real size rather than guessing.
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path


HEADER = """#include <stdint.h>

/* Generated by tools/generate_script_bank.py - do not edit by hand.
 * src/resources.c far_call_bank()s directly into {fetch_fn}, which
 * switches on script_fetch_query_kind/id (set by the resident caller) to
 * pick which resource below to copy from - see that file's header comment
 * for why one shared bank beats one far_call_bank() per resource. */

extern uint8_t script_fetch_query_kind;
extern uint8_t script_fetch_query_id;
extern uint16_t script_fetch_query_start;
extern uint8_t* script_fetch_query_dest;
extern uint16_t script_fetch_query_capacity;
extern uint16_t script_fetch_result_length;
extern uint16_t script_fetch_copied_length;

#pragma section( {bank_sym}_code, 0 )
#pragma section( {bank_sym}_data, 0 )
#pragma region( {bank_sym}_bank, 0x8000, 0xc000, , {bank}u, {{ {bank_sym}_data, {bank_sym}_code }} )
#pragma code({bank_sym}_code)
#pragma data({bank_sym}_data)

"""

ARRAY_TEMPLATE = """static const uint8_t {sym}[{size}] = {{
#embed {size} "{embed_path}"
}};

"""

FETCH_HEADER = """__noinline void {fetch_fn}(void) {{
    uint16_t start = script_fetch_query_start;
    uint16_t capacity = script_fetch_query_capacity;
    const uint8_t* source;
    uint16_t total;
    uint16_t available;
    uint16_t copy_count;
    uint16_t i;

    switch (script_fetch_query_id) {{
"""

CASE_TEMPLATE = """        case {resource_id}u: source = {sym}; total = {size}u; break;
"""

FETCH_FOOTER = """        default:
            script_fetch_result_length = 0u;
            script_fetch_copied_length = 0u;
            return;
    }

    script_fetch_result_length = total;
    if (start >= total) {
        script_fetch_copied_length = 0u;
        return;
    }
    available = total - start;
    copy_count = available < capacity ? available : capacity;
    for (i = 0u; i < copy_count; ++i) {
        script_fetch_query_dest[i] = source[start + i];
    }
    script_fetch_copied_length = copy_count;
}

#pragma code(code)
#pragma data(data)
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, action="append", required=True,
                         metavar="ID=PATH",
                         help="one resource: numeric ID and its compiled .bin path, e.g. 0=build/scripts/00.bin (repeatable)")
    parser.add_argument("--output", type=Path, required=True,
                         help="C file to write (its own directory is where #embed's relative path resolves from)")
    parser.add_argument("--bank-symbol", required=True,
                         help="C identifier prefix for this bank's sections/region")
    parser.add_argument("--fetch-fn", required=True,
                         help="name of the generated shared fetch function")
    parser.add_argument("--bank", type=int, required=True,
                         help="EasyFlash bank number (0-63) all these resources share")
    args = parser.parse_args()

    entries = []
    for raw in args.input:
        resource_id_str, _, path_str = str(raw).partition("=")
        if not path_str:
            raise SystemExit(f"--input {raw!r}: expected ID=PATH")
        resource_id = int(resource_id_str)
        path = Path(path_str)
        size = path.stat().st_size
        if size == 0:
            raise SystemExit(f"{path}: empty, nothing to embed")
        entries.append((resource_id, path, size))

    total = sum(size for _, _, size in entries)
    if total > 0x4000:
        raise SystemExit(f"{total} bytes total, too big for one 16 KiB bank")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    out_dir = args.output.resolve().parent

    parts = [HEADER.format(fetch_fn=args.fetch_fn, bank_sym=args.bank_symbol,
                            bank=args.bank)]
    cases = []
    for resource_id, path, size in entries:
        sym = f"{args.bank_symbol}_res_{resource_id}"
        embed_path = path.resolve()
        try:
            embed_rel = embed_path.relative_to(out_dir)
        except ValueError:
            embed_rel = Path(os.path.relpath(embed_path, out_dir))
        parts.append(ARRAY_TEMPLATE.format(sym=sym, size=size,
                                            embed_path=embed_rel.as_posix()))
        cases.append(CASE_TEMPLATE.format(resource_id=resource_id, sym=sym, size=size))

    parts.append(FETCH_HEADER.format(fetch_fn=args.fetch_fn))
    parts.extend(cases)
    parts.append(FETCH_FOOTER)

    args.output.write_text("".join(parts), encoding="utf-8")
    print(f"{len(entries)} resource(s), {total} bytes total -> {args.output} [bank {args.bank}]")


if __name__ == "__main__":
    main()
